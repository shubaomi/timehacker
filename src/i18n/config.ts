export function resolveLocale(value: string | null | undefined): Locale {
  return value?.toLowerCase().includes("zh") ? "zh" : "en";
}

export function localeTag(locale: Locale): "en" | "zh-Hans" {
  return locale === "zh" ? "zh-Hans" : "en";
}

